        <h5 class="text-center">Child Care & Protection Policies</h5>
        <p style="text-align: justify;">Child abuse and neglect are concerns throughout the world. Child abuse and neglect are violations of a child’s human rights and are obstacles to the child’s education as well as to their physical, emotional, and spiritual development.</p>

<p style="text-align: justify;">SGGS endorses the Rights of the Child, as per the prevailing Child Protection Act.</p>

<p style="text-align: justify;">Schools have a special institutional role in society as protectors of children. Schools need to ensure that all children in their care are afforded a safe and secure environment in which to grow and develop, both at school and away. Educators, having the opportunity to observe and interact with children over time, are in a unique position to identify children who are in need of help and protection. As such, educators have a professional and ethical obligation to identify children who are in need of help and protection, and to take steps to ensure that the child and family avail themselves of the services needed to remedy any situation that constitutes child abuse or neglect.</p>

<p style="text-align: justify;">All staff employed at SGGS must report suspected incidents of child abuse or neglect whenever the staff member has reasonable cause to believe that a child has suffered, or is at significant risk of suffering abuse or neglect. Reporting and follow-up of all suspected incidents of child abuse or neglect will proceed in accordance with administrative regulations respective to this policy. Furthermore, cases of suspected child abuse or neglect may be reported to the appropriate employer, to the respective Cells / Agencies in the Local Authorities and / or to the appropriate child protection agency in the Country.</p>

<p style="text-align: justify;">SGGS seeks to be a safe haven for students who may be experiencing abuse or neglect in any aspect of their lives. As such, SGGS distributes this policy annually to all parents and applicants and provides training to all staff working at SGGS and will continue to make every effort to implement hiring practices to ensure the safety of children, and will review the policy annually for compliance and effectiveness.</p>

<p style="text-align: justify;">In the case of a staff member reported as an alleged offender, SGGS will conduct a full investigation following a carefully designed course of due process, keeping the safety of the child at the highest priority.</p>

